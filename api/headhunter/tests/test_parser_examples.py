"""
Примеры использования парсеров вакансий без Celery
"""

import os
import django

os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'src.config.patterns.development')
django.setup()

from modules.vacancies_parser.api.headhunter.scripts import parse_vacancies_by_text, parse_all_vacancies

# ============================================================
# ПРИМЕР 1: Парсинг по конкретным запросам
# ============================================================
def example_1_by_text():
    """Парсинг вакансий по текстовым запросам"""
    print('\n=== Пример 1: Парсинг по текстовым запросам ===')

    result = parse_vacancies_by_text(
        text_list=['Python', 'JavaScript', 'Java'],  # Несколько запросов
        area=1,  # Москва (1), СПб (2), Россия (113)
        pages=2,  # 2 страницы по 100 вакансий на каждый запрос
        delay=1.0,
        get_details=True
    )

    print(f'Результат: {result}')


# ============================================================
# ПРИМЕР 2: Парсинг только названий (быстро, без деталей)
# ============================================================
def example_2_fast():
    """Быстрый парсинг без детальной информации"""
    print('\n=== Пример 2: Быстрый парсинг (без деталей) ===')

    result = parse_vacancies_by_text(
        text_list=['Data Scientist'],
        area=113,  # Россия
        pages=1,
        delay=0.5,
        get_details=False  # Без деталей - быстрее
    )

    print(f'Результат: {result}')


# ============================================================
# ПРИМЕР 3: Универсальный парсинг (по регионам)
# ============================================================
def example_3_universal():
    """Универсальный парсинг по всем регионам"""
    print('\n=== Пример 3: Универсальный парсинг ===')
    print('ВНИМАНИЕ: Это займет много времени!')

    result = parse_all_vacancies(
        pages_per_area=1,  # Страниц на регион
        delay=2.0,
        max_total_pages=10,  # Максимум страниц
        areas_only=True  # Только по регионам
    )

    print(f'Результат: {result}')


# ============================================================
# ЗАПУСК ПРИМЕРОВ
# ============================================================
if __name__ == '__main__':
    example_1_by_text()  # Основной пример
